export const MINIMUM_LEAD_DAYS = 5;
export const emptyCake = () => ({ mass: '', fillings: [], size: '', celebration: '', theme: '' });
export function minimumOrderDate(now = new Date()) {
  const day = new Date(now.getFullYear(), now.getMonth(), now.getDate() + MINIMUM_LEAD_DAYS);
  return `${day.getFullYear()}-${String(day.getMonth() + 1).padStart(2, '0')}-${String(day.getDate()).padStart(2, '0')}`;
}
export function displayDate(value) {
  if (!value) return 'A combinar';
  const [year, month, day] = value.split('-');
  return `${day}/${month}/${year}`;
}
export function validateDetails(idea, minDate = minimumOrderDate()) {
  if (idea.date && idea.date < minDate)
    return 'As encomendas precisam de pelo menos 5 dias de antecedência. Escolha outra data ou deixe a combinar.';
  if (
    idea.people &&
    (!Number.isInteger(Number(idea.people)) ||
      Number(idea.people) < 1 ||
      Number(idea.people) > 10000)
  )
    return 'Informe entre 1 e 10.000 pessoas ou deixe a quantidade em aberto.';
  if (idea.interestId === 'custom-cake' && idea.cake) {
    if (idea.cake.mass && !cakeMasses.includes(idea.cake.mass))
      return 'Escolha uma das massas disponíveis ou deixe a combinar.';
    if (idea.cake.size && !cakeSizes.some((size) => size.id === idea.cake.size))
      return 'Escolha um tamanho disponível ou deixe a combinar.';
    if (idea.cake.fillings.length > 2) return 'Escolha no máximo 2 preferências de recheio.';
    if (idea.cake.fillings.some((filling) => !cakeFillings.includes(filling)))
      return 'Confira as preferências de recheio escolhidas.';
  }
  return '';
}
